test('reports the actual cancellation response for an active C/B turn', async ({ page }) => {
  test.setTimeout(240_000)
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/assessment', { waitUntil: 'domcontentloaded' })
  await expect(page.getByText('C 服务在线')).toBeVisible({ timeout: 20_000 })
  await expect(page.locator('.chat-composer textarea')).toBeEnabled({ timeout: 20_000 })
  await page.getByRole('button', { name: /提交评估/ }).click()
  const cancel = page.locator('.turn-running button')
  await expect(cancel).toBeVisible({ timeout: 30_000 })
  await cancel.click()
  const warning = page.getByText('B 求解已经开始，C 未能取消任务；后台求解可能仍会继续。')
  const status = page.locator('.chat-agent-message .status-chip').last()
  await expect.poll(async () => (await warning.isVisible()) || (await status.textContent())?.trim() === '已取消', { timeout: 20_000 }).toBeTruthy()
})

test('explains the B source-version mismatch for East District and Xiaolan', async ({ page }) => {
  test.setTimeout(180_000)
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/')
  for (const [regionId, town] of [['east_district', '东区街道'], ['xiaolan', '小榄镇']]) {
    await page.locator('.region-picker').click()
    await page.locator('.region-menu button').filter({ hasText: regionId }).click()
    await expect(page.locator('.region-picker strong')).toHaveText(town)
    await expect(page.locator('.chat-composer textarea')).toBeEnabled({ timeout: 20_000 })
    await page.goto('/assessment')
    await expect(page.locator('.chat-composer textarea')).toBeEnabled({ timeout: 20_000 })
    await page.getByRole('button', { name: /提交评估/ }).click()
    const result = page.locator('.chat-agent-message').last()
    await expect(result.locator('.status-chip')).toHaveText('未完成', { timeout: 30_000 })
    await expect(result).toContainText('当前 B 服务没有加载对应数据源')
    await expect(result.locator('.error-details')).toContainText('B_SCENARIO_INVALID')
  }
})
